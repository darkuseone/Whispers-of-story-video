def s_curve(v: float, amount: float) -> float:
    """
    Мягкая S вокруг 0.5. amount=0 — прямая, 0.2 — заметный контраст.

    Считается через тот же сглаживающий полином, что и движение камеры
    (3p^2-2p^3): он даёт плавные концы без изломов на чёрном и белом.
    """
    if amount <= 0:
        return v
    smooth = v * v * (3.0 - 2.0 * v)
    return v + (smooth - v) * amount


def grade(r, g, b, lift, gain, gamma, sat, contr):
    out = []
    for c, lf, gn, gm in zip((r, g, b), lift, gain, gamma):
        # подъём чёрного: тень перестаёт быть провалом, вся шкала сжимается
        # к верху, поэтому дальше нормируем на (1-lf)
        c = lf + c * (1.0 - lf)
        c = pow(max(c, 0.0), gm) * gn
        out.append(min(max(c, 0.0), 1.0))

    # насыщенность вокруг светимости по Rec.709
    y = 0.2126 * out[0] + 0.7152 * out[1] + 0.0722 * out[2]
    out = [min(max(y + (c - y) * sat, 0.0), 1.0) for c in out]

    return [min(max(s_curve(c, contr), 0.0), 1.0) for c in out]


def write_cube(name: str, params: dict, title: str, out_dir: Path):
    lines = [f"# {title}", f'TITLE "{name}"', f"LUT_3D_SIZE {SIZE}",
             "DOMAIN_MIN 0.0 0.0 0.0", "DOMAIN_MAX 1.0 1.0 1.0", ""]
    n = SIZE - 1
    # порядок обхода в .cube: быстрее всего меняется КРАСНЫЙ, медленнее синий
    for bi in range(SIZE):
        for gi in range(SIZE):
            for ri in range(SIZE):
                rgb = grade(ri / n, gi / n, bi / n, **params)
                lines.append(" ".join(f"{c:.6f}" for c in rgb))
    (out_dir / f"{name}.cube").write_text("\n".join(lines) + "\n")
    return out_dir / f"{name}.cube"


