"""
make_luts.py — генератор цветокоров канала.

Запускается разово, результат (.cube) лежит в репозитории:

    python pipeline/make_luts.py

Зачем генератор, а не файлы руками: .cube это 4913 строк чисел, править их
невозможно, а объяснить «почему такой оттенок» нужно. Здесь каждый цветокор
описан пятью понятными числами, из которых таблица и считается.

Семья канала — ХОЛОДНАЯ. Тёплая янтарная семья (warm_amber, oak_brass,
lamp_glow, dust_gold, copper_dusk) делалась под канал о находках и лавке
древностей и убрана целиком: она была бы визуальным близнецом соседнего
канала, а два канала одного владельца зритель сравнивает первым делом.

Здесь ночь: лунный камень, индиго над рекой, стылая бирюза моря, пепел
известняка. Ролик включают перед сном — тёплый жёлтый свет бодрит, холодный
синий укладывает. Это не метафора: свет с высокой цветовой температурой в
кадре читается как вечер и покой, ровно поэтому «ночной режим» экранов
работает наоборот.

Отдельно живёт архивная семья: подлинное фото и хроника красятся ДРУГИМ
цветокором, чтобы зритель на уровне ощущения отличал настоящее от
восстановленного. Раз основная семья холодная, архивная разведена с ней не
температурой (она тоже холодная), а плотностью: заметно ниже насыщенность,
выше контраст — картинка читается как отпечаток, а не как кадр.

Порядок операций внутри одного цветокора:
  1. lift  — подъём чёрного по каналам (матовая плёночная тень)
  2. gain  — множитель светов по каналам (оттенок бликов)
  3. gamma — средние тона по каналам (основной характер картинки)
  4. sat   — насыщенность вокруг светимости
  5. contr — мягкая S-кривая вокруг середины

Насыщенность и контраст держатся СЛАБЫМИ намеренно. Поверх LUT в build.py
ложится ещё плёночная база film_look(), зерно и виньетка; цветокор в полную
силу тут перебивает всё, что идёт после него.
"""

