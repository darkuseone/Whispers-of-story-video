def measure(params: dict) -> tuple:
    """
    Проверка ХОЛОДА замером, а не на глаз.

    Возвращает (R−B на серой шкале, средняя светимость). Отрицательное
    первое число означает, что серый уходит в синий: у тёплого канала эта
    же величина была от +10 до +25, здесь она обязана быть отрицательной у
    всех цветокоров, кроме bronze_frost, — он разведён по температуре
    сознательно и на серой шкале выходит около нуля.
    """
    diffs, lums = [], []
    for k in range(1, 16):
        v = k / 16.0
        r, g, b = grade(v, v, v, **params)
        diffs.append((r - b) * 255)
        lums.append((0.2126 * r + 0.7152 * g + 0.0722 * b) * 255)
    return sum(diffs) / len(diffs), sum(lums) / len(lums)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, p in {**COLD, **ARCHIVE}.items():
        path = write_cube(name, p, TITLES[name], OUT)
        rb, lum = measure(p)
        print(f"{path.name:<24} {path.stat().st_size // 1024:>4} КБ   "
              f"R−B {rb:+6.1f}   яркость {lum:5.1f}")


if __name__ == "__main__":
    main()
